const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = process.argv[2] || require('node:path').join(__dirname, '..', 'index.html');
const html = fs.readFileSync(path, 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
const ctx = vm.createContext({localStorage:{getItem:()=>null,setItem(){}},document:{addEventListener(){}},location:{hash:''}});
for (const file of ['data/menus.js','menu-utils.js']) vm.runInContext(fs.readFileSync(require('node:path').join(require('node:path').dirname(path),file),'utf8'),ctx);
vm.runInContext(script.replace(/show\(VIEWS\[hash\][^\n]+/, ''), ctx);
const run = expr => vm.runInContext(expr, ctx);
assert.equal(run('TOTAL'),17,'見送りのカップ1個を購入予定数から除外');
assert.equal(run('Object.keys(ITEMS).length'),9,'見送り商品もリストに残す');
assert.match(run("cardHTML('cup')"),/<s>リルリンリン スーベニアカップ<\/s>/);
assert.match(run("cardHTML('cup')"),/今回は買わない/);
assert.doesNotMatch(run("cardHTML('cup')"),/class="tick"/,'見送り商品に購入チェックは出さない');
assert.equal(run("onlyLeft=false; matchesList('cup')"),true,'ぜんぶではカップを表示');
assert.equal(run("onlyLeft=true; matchesList('cup')"),false,'未購入ではカップを除外');
assert.equal(run("Object.keys(ITEMS).filter(matchesList).length"),8);
assert.equal(run("done={cup:true}; purchasedCount()"),0,'旧カップチェックを購入数へ加算しない');
assert.equal(run("done={cup:true,mug:true}; purchasedCount()"),1,'他商品の保存済みチェックは維持');
assert.equal(run("matchesList('mug')"),false);
assert.equal(run("done=Object.fromEntries(Object.keys(ITEMS).map(k=>[k,true])); purchasedCount()"),17,'全購入でも17個');
assert.equal(run("Object.keys(ITEMS).filter(matchesList).length"),0);
run('done={}; onlyLeft=false');
assert.match(run('VIEWS.where()'),/<s>カップ<\/s>（見送り）/);
assert.match(run('VIEWS.how()'),/<s>カップ<\/s>（見送り）/);
for(const k of ['charm','figure','mug','cap']) {
  assert.match(run(`cardHTML('${k}')`),/アプリ必要：入店パス/,'ショップは入店パスを明示');
  assert.match(run(`cardHTML('${k}')`),/列に注意：入店・レジ/);
}
assert.match(run("cardHTML('badge')"),/店頭の列なし/);
assert.match(run("cardHTML('badge')"),/アプリ限定：配送注文/);
assert.match(run("cardHTML('gummy')"),/アプリ：店舗による/);
assert.match(run("cardHTML('bucket')"),/アプリ不要：直接購入/);
for(const k of ['arendelle','snuggly','lookout']) assert.match(run(`placeHTML('${k}')`),/アプリ必要：モバイル注文/);
for(const k of ['zambini','refrescos','nydeli','hudson','bayside','yucatan','casbah','sebastian']) assert.match(run(`placeHTML('${k}')`),/アプリ任意：モバイル注文可/);
for(const k of ['portofino','biscotti','liberty','horizon','vulcania','pcDock','pcLido','pcLiberty','pcSoaring','pcHorizon','pcTink']) assert.match(run(`placeHTML('${k}')`),/アプリ不要：店頭注文/);
assert.equal(run("Object.keys(ITEMS).filter(k => matchesNeed(k,'queue')).length"),8);
assert.equal(run("Object.keys(ITEMS).filter(k => matchesNeed(k,'app')).length"),6);
assert.equal(run("Object.keys(ITEMS).filter(k => matchesNeed(k,'noapp')).length"),4);
assert.equal(run("matchesNeed('gummy','app') && matchesNeed('gummy','noapp')"),true,'店舗による品は両方で見つかる');
assert.equal(run("matchesNeed('badge','queue')"),false);
assert.match(run('VIEWS.rules()'),/2026年11月2日/);
assert.match(run('VIEWS.how()'),/モバイルオーダー/);
assert.deepEqual(Array.from(run('commonFoodPlaces()')),['zambini','hudson','casbah','sebastian'],'購入予定2種類の共通4店');
assert.deepEqual(Array.from(run("foodItemsAt('zambini')")),['tumbler','gummy'],'見送りカップは共通判定から除外');
for (const k of ['nydeli','yucatan','bayside','arendelle','mcduck','pcDock']) {
  assert.equal(run(`commonFoodPlaces().includes('${k}')`),false,'1種類・ショップ・ワゴンを共通店にしない');
}
assert.equal(run('done={tumbler:true}; commonFoodPlaces().length'),4,'購入済みでも取扱店情報を残す');
run('done={}');
assert.equal(run('ITEMS.cup.skipped=false; commonFoodPlaces().length'),6,'購入予定に戻した品は販売場所から自動集計');
run('ITEMS.cup.skipped=true');
assert.match(run('commonFoodHTML()'),/タンブラー/);
assert.match(run('commonFoodHTML()'),/グミケース/);
assert.match(run('commonFoodHTML()'),/対象ドリンク/);
assert.match(run('VIEWS.where()'),/まとめて買えるレストラン/);
assert.match(run('VIEWS.list()'),/まとめて買える4店を見る/);
assert.match(run('VIEWS.how()'),/まとめて買える4店を見る/);
assert.match(run("placeHTML('zambini')"),/スーベニア2種類をまとめて/);
assert.doesNotMatch(run("placeHTML('nydeli')"),/スーベニア2種類をまとめて/);
console.log('PASS: 商品9区分・店舗25か所、カップ見送り・購入予定17個、共通レストラン4店');
